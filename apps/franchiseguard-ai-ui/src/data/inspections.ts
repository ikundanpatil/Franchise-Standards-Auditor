/** Inspections dated today — falls back to the latest active day so the
 *  dashboard is never empty during a demo. */
export function todaysInspections(now = new Date()): InspectionRecord[] {
	const key = now.toISOString().slice(0, 10);
	const exact = INSPECTIONS.filter((i) => i.date.slice(0, 10) === key);
	if (exact.length) return exact;
	const latestDay = INSPECTIONS.filter((i) => i.status !== 'scheduled')
		.map((i) => i.date.slice(0, 10))
		.sort()
		.pop();
	return INSPECTIONS.filter((i) => i.date.slice(0, 10) === latestDay);
}


export const storeById = (id: string): Store | undefined => STORES.find((s) => s.id === id);

export const REGIONS: string[] = Array.from(new Set(STORES.map((s) => s.region)));

/** Store count grouped by risk level. */
export function riskDistribution(): Record<Store['risk'], number> {
	return STORES.reduce(
		(acc, s) => {
			acc[s.risk] += 1;
			return acc;
		},
		{ low: 0, medium: 0, high: 0, critical: 0 } as Record<Store['risk'], number>,
	);
}

/** Store count grouped by region. */
export function regionCounts(): Array<{ region: string; count: number; avgScore: number }> {
	return REGIONS.map((region) => {
		const inRegion = STORES.filter((s) => s.region === region);
		const avg = Math.round(inRegion.reduce((sum, s) => sum + s.complianceScore, 0) / inRegion.length);
		return { region, count: inRegion.length, avgScore: avg };
	});
}
